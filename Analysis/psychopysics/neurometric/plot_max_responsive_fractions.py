def perform_statistical_analysis(data, output_dir):
    """Perform statistical tests comparing sigmoid vs gaussian max responsive fractions."""
    print("\n" + "="*50)
    print("STATISTICAL ANALYSIS")
    print("="*50)
    
    # Per-mouse comparison (paired test) - comparing means per mouse
    sigmoid_means = np.array(data['sigmoid_means_per_mouse'])
    gaussian_means = np.array(data['gaussian_means_per_mouse'])
    
    print(f"\n1. PER-MOUSE COMPARISON (n={len(sigmoid_means)} mice)")
    print(f"   Sigmoid means: {sigmoid_means}")
    print(f"   Gaussian means: {gaussian_means}")
    
    # Check if we have the same number of mice for both conditions
    if len(sigmoid_means) != len(gaussian_means):
        print(f"   WARNING: Different number of mice with sigmoid ({len(sigmoid_means)}) vs gaussian ({len(gaussian_means)}) data")
        # Use only mice that have both sigmoid and gaussian data
        min_mice = min(len(sigmoid_means), len(gaussian_means))
        sigmoid_means = sigmoid_means[:min_mice]
        gaussian_means = gaussian_means[:min_mice]
        print(f"   Using first {min_mice} mice for paired comparison")
    
    # Paired statistical test (comparing per-mouse means)
    try:
        p_paired, test_label_paired, info_paired = choose_test(sigmoid_means, gaussian_means, paired=True, mode="auto")
        rep_paired = info_paired["report"]
        
        print(f"\n   Statistical Test: {rep_paired['test']}")
        print(f"   {rep_paired['statistic_name']} = {rep_paired['statistic_value']:.4f}")
        if rep_paired['df'] is not None:
            print(f"   df = {rep_paired['df']}")
        print(f"   p = {rep_paired['p']:.6f}")
        print(f"   Effect size ({rep_paired['effect_size']['name']}) = {rep_paired['effect_size']['value']:.4f}")
        if rep_paired["ci"]:
            print(f"   95% CI for {rep_paired['ci']['parameter']}: [{rep_paired['ci']['low']:.4f}, {rep_paired['ci']['high']:.4f}]")
        
        paired_success = True
    except Exception as e:
        print(f"   Error in paired test: {e}")
        print("   Skipping paired Analysis")
        paired_success = False
        rep_paired = None
    
    # Overall pooled comparison (independent test) - comparing all individual neurons
    sigmoid_all = np.array(data['all_sigmoid_fractions'])
    gaussian_all = np.array(data['all_gaussian_fractions'])
    
    print(f"\n2. POOLED NEURON COMPARISON")
    print(f"   Sigmoid neurons: n={len(sigmoid_all)}, mean={np.mean(sigmoid_all):.4f}, std={np.std(sigmoid_all):.4f}")
    print(f"   Gaussian neurons: n={len(gaussian_all)}, mean={np.mean(gaussian_all):.4f}, std={np.std(gaussian_all):.4f}")
    
    # Independent statistical test (comparing all individual neurons)
    try:
        p_indep, test_label_indep, info_indep = choose_test(sigmoid_all, gaussian_all, paired=False, mode="auto")
        rep_indep = info_indep["report"]
        
        print(f"\n   Statistical Test: {rep_indep['test']}")
        print(f"   {rep_indep['statistic_name']} = {rep_indep['statistic_value']:.4f}")
        if rep_indep['df'] is not None:
            print(f"   df = {rep_indep['df']:.2f}")
        print(f"   p = {rep_indep['p']:.6f}")
        print(f"   Effect size ({rep_indep['effect_size']['name']}) = {rep_indep['effect_size']['value']:.4f}")
        if rep_indep["ci"]:
            print(f"   95% CI for {rep_indep['ci']['parameter']}: [{rep_indep['ci']['low']:.4f}, {rep_indep['ci']['high']:.4f}]")
        
        indep_success = True
    except Exception as e:
        print(f"   Error in independent test: {e}")
        print("   Skipping independent Analysis")
        indep_success = False
        rep_indep = None
    
    # Additional descriptive statistics
    print(f"\n3. DESCRIPTIVE STATISTICS")
    print(f"   Per-mouse sigmoid mean: {np.mean(sigmoid_means):.4f} ± {np.std(sigmoid_means):.4f}")
    print(f"   Per-mouse gaussian mean: {np.mean(gaussian_means):.4f} ± {np.std(gaussian_means):.4f}")
    print(f"   Overall sigmoid mean: {np.mean(sigmoid_all):.4f} ± {np.std(sigmoid_all):.4f}")
    print(f"   Overall gaussian mean: {np.mean(gaussian_all):.4f} ± {np.std(gaussian_all):.4f}")
    
    # Save statistical results to file
    stats_results = {}
    
    if paired_success:
        stats_results['Per_Mouse_Analysis'] = {
            'test': rep_paired['test'],
            'statistic': rep_paired['statistic_value'],
            'df': rep_paired['df'],
            'p_value': rep_paired['p'],
            'effect_size_name': rep_paired['effect_size']['name'],
            'effect_size_value': rep_paired['effect_size']['value'],
            'ci_low': rep_paired['ci']['low'] if rep_paired['ci'] else None,
            'ci_high': rep_paired['ci']['high'] if rep_paired['ci'] else None,
            'n_mice': len(sigmoid_means),
            'sigmoid_mean': np.mean(sigmoid_means),
            'gaussian_mean': np.mean(gaussian_means)
        }
    else:
        stats_results['Per_Mouse_Analysis'] = {
            'test': 'Failed',
            'error': 'Could not perform paired test',
            'n_mice': len(sigmoid_means),
            'sigmoid_mean': np.mean(sigmoid_means),
            'gaussian_mean': np.mean(gaussian_means)
        }
    
    if indep_success:
        stats_results['Pooled_Neuron_Analysis'] = {
            'test': rep_indep['test'],
            'statistic': rep_indep['statistic_value'],
            'df': rep_indep['df'],
            'p_value': rep_indep['p'],
            'effect_size_name': rep_indep['effect_size']['name'],
            'effect_size_value': rep_indep['effect_size']['value'],
            'ci_low': rep_indep['ci']['low'] if rep_indep['ci'] else None,
            'ci_high': rep_indep['ci']['high'] if rep_indep['ci'] else None,
            'n_sigmoid': len(sigmoid_all),
            'n_gaussian': len(gaussian_all),
            'sigmoid_mean': np.mean(sigmoid_all),
            'gaussian_mean': np.mean(gaussian_all)
        }
    else:
        stats_results['Pooled_Neuron_Analysis'] = {
            'test': 'Failed',
            'error': 'Could not perform independent test',
            'n_sigmoid': len(sigmoid_all),
            'n_gaussian': len(gaussian_all),
            'sigmoid_mean': np.mean(sigmoid_all),
            'gaussian_mean': np.mean(gaussian_all)
        }
    
    # Save to CSV
    stats_rows = []
    
    if paired_success:
        stats_rows.append({
            'Analysis': 'Per-Mouse (Paired)',
            'Test': rep_paired['test'],
            'Statistic': rep_paired['statistic_value'],
            'df': rep_paired['df'],
            'p_value': rep_paired['p'],
            'Effect_Size': f"{rep_paired['effect_size']['name']}: {rep_paired['effect_size']['value']:.4f}",
            'N': len(sigmoid_means),
            'Sigmoid_Mean': np.mean(sigmoid_means),
            'Gaussian_Mean': np.mean(gaussian_means)
        })
    
    if indep_success:
        stats_rows.append({
            'Analysis': 'Pooled Neurons (Independent)',
            'Test': rep_indep['test'],
            'Statistic': rep_indep['statistic_value'],
            'df': rep_indep['df'],
            'p_value': rep_indep['p'],
            'Effect_Size': f"{rep_indep['effect_size']['name']}: {rep_indep['effect_size']['value']:.4f}",
            'N': f"Sigmoid: {len(sigmoid_all)}, Gaussian: {len(gaussian_all)}",
            'Sigmoid_Mean': np.mean(sigmoid_all),
            'Gaussian_Mean': np.mean(gaussian_all)
        })
    
    if stats_rows:
        stats_df = pd.DataFrame(stats_rows)
        stats_file = join(output_dir, 'statistical_analysis_results.csv')
        stats_df.to_csv(stats_file, index=False)
        print(f"\nStatistical results saved to: {stats_file}")
    
    return stats_results

