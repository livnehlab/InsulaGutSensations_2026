def create_per_mouse_comparison_plot(data, output_dir):
    """Create bar plot comparing per-mouse mean max responsive fractions."""
    sigmoid_means = np.array(data['sigmoid_means_per_mouse'])
    gaussian_means = np.array(data['gaussian_means_per_mouse'])
    mouse_ids = data['mouse_ids']
    
    # Calculate overall statistics
    mean_sigmoid = np.mean(sigmoid_means)
    mean_gaussian = np.mean(gaussian_means)
    sem_sigmoid = st.sem(sigmoid_means)
    sem_gaussian = st.sem(gaussian_means)
    
    # Create the plot
    plt.figure(figsize=(10, 6))
    
    # Bar positions
    x_positions = [0, 1]
    colors = ['gray', 'tan']
    labels = ['Sigmoid', 'Gaussian']
    means = [mean_sigmoid, mean_gaussian]
    sems = [sem_sigmoid, sem_gaussian]
    
    # Create bars with error bars
    bars = plt.bar(x_positions, means, yerr=sems, 
                   color=colors, alpha=0.6, width=0.6, 
                   capsize=5, error_kw={'linewidth': 2})
    
    # Add individual mouse data points with connecting lines
    for i in range(len(mouse_ids)):
        mouse_values = [sigmoid_means[i], gaussian_means[i]]
        plt.plot(x_positions, mouse_values, 'o-', color='black', 
                alpha=0.4, linestyle='--', markersize=6, linewidth=1.5)
    
    # Add individual data points as scatter
    plt.scatter([0] * len(sigmoid_means), sigmoid_means, 
               color='darkgray', alpha=0.7, s=40, edgecolors='white', linewidth=1, zorder=3)
    plt.scatter([1] * len(gaussian_means), gaussian_means, 
               color='saddlebrown', alpha=0.7, s=40, edgecolors='white', linewidth=1, zorder=3)
    
    # Add text annotations showing exact values
    for i, (pos, mean_val, sem_val) in enumerate(zip(x_positions, means, sems)):
        plt.text(pos, mean_val + sem_val + 0.02, f'{mean_val:.3f} ± {sem_val:.3f}', 
                ha='center', va='bottom', fontsize=10, fontweight='bold')
    
    # Formatting
    plt.xticks(x_positions, labels)
    plt.ylabel('Mean Max Responsive Fraction')
    plt.title('Max Responsive Fractions: Sigmoid vs Gaussian\n(Mean ± SEM across mice)')
    plt.ylim(0, max(means) + max(sems) + 0.1)
    
    # Add mouse labels
    for i, mouse_id in enumerate(mouse_ids):
        plt.text(0.5, 0.05 + i * 0.03, f'{mouse_id}', ha='center', va='bottom', 
                fontsize=8, transform=plt.gca().transAxes)
    
    plt.tight_layout()
    
    # Save the plot
    plot_path = join(output_dir, 'max_responsive_fractions_per_mouse_comparison.pdf')
    plt.savefig(plot_path)
    plt.close()
    print(f"Per-mouse comparison plot saved to: {plot_path}")
    
    return mean_sigmoid, mean_gaussian, sem_sigmoid, sem_gaussian

def create_distribution_comparison_plot(data, output_dir):
    """Create histogram/density plot comparing distributions of max responsive fractions."""
    sigmoid_all = np.array(data['all_sigmoid_fractions'])
    gaussian_all = np.array(data['all_gaussian_fractions'])
    
    plt.figure(figsize=(12, 6))
    
    # Create histogram with density overlay
    plt.hist(sigmoid_all, bins=30, density=True, color='gray', alpha=0.5, label='Sigmoid')
    plt.hist(gaussian_all, bins=30, density=True, color='tan', alpha=0.5, label='Gaussian')
    
    # Add KDE density lines
    if len(sigmoid_all) > 1:
        density_sigmoid = gaussian_kde(sigmoid_all)
        xs_sigmoid = np.linspace(sigmoid_all.min(), sigmoid_all.max(), 100)
        density_sigmoid.covariance_factor = lambda: 0.1
        density_sigmoid._compute_covariance()
        plt.plot(xs_sigmoid, density_sigmoid(xs_sigmoid), color='gray', linewidth=2, label='Sigmoid KDE')
    
    if len(gaussian_all) > 1:
        density_gaussian = gaussian_kde(gaussian_all)
        xs_gaussian = np.linspace(gaussian_all.min(), gaussian_all.max(), 100)
        density_gaussian.covariance_factor = lambda: 0.1
        density_gaussian._compute_covariance()
        plt.plot(xs_gaussian, density_gaussian(xs_gaussian), color='tan', linewidth=2, label='Gaussian KDE')
    
    # Add vertical lines for means
    plt.axvline(np.mean(sigmoid_all), color='gray', linestyle='--', alpha=0.8, linewidth=2)
    plt.axvline(np.mean(gaussian_all), color='tan', linestyle='--', alpha=0.8, linewidth=2)
    
    # Formatting
    plt.xlabel('Max Responsive Fraction')
    plt.ylabel('Density')
    plt.title(f'Distribution of Max Responsive Fractions\nSigmoid: n={len(sigmoid_all)}, Gaussian: n={len(gaussian_all)}')
    plt.legend()
    plt.grid(True, alpha=0.3)
    
    plt.tight_layout()
    
    # Save the plot
    plot_path = join(output_dir, 'max_responsive_fractions_distribution_comparison.pdf')
    plt.savefig(plot_path)
    plt.close()
    print(f"Distribution comparison plot saved to: {plot_path}")

def create_violin_plot_comparison(data, output_dir):
    """Create violin plot comparing max responsive fractions."""
    sigmoid_all = np.array(data['all_sigmoid_fractions'])
    gaussian_all = np.array(data['all_gaussian_fractions'])
    
    plt.figure(figsize=(8, 6))
    
    # Create violin plot
    parts = plt.violinplot([sigmoid_all, gaussian_all], positions=[0, 1], widths=0.6, 
                          showmeans=True, showmedians=True)
    
    # Color the violin plots
    colors = ['gray', 'tan']
    for pc, color in zip(parts['bodies'], colors):
        pc.set_facecolor(color)
        pc.set_alpha(0.6)
    
    # Add individual data points (sample if too many)
    max_points = 100  # Limit number of points for visibility
    
    for i, (data_array, color) in enumerate(zip([sigmoid_all, gaussian_all], colors)):
        if len(data_array) > max_points:
            # Sample points for display
            indices = np.random.choice(len(data_array), max_points, replace=False)
            sample_data = data_array[indices]
        else:
            sample_data = data_array
            
        # Add jitter to x-position
        x_jitter = np.random.normal(i, 0.05, len(sample_data))
        plt.scatter(x_jitter, sample_data, alpha=0.4, s=20, color=color, edgecolors='white', linewidth=0.5)
    
    # Formatting
    plt.xticks([0, 1], ['Sigmoid', 'Gaussian'])
    plt.ylabel('Max Responsive Fraction')
    plt.title('Distribution of Max Responsive Fractions\n(Violin Plot with Sample Data Points)')
    
    # Add sample size annotations
