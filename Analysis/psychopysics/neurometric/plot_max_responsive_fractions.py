def load_max_fraction_data(mice, days):
    """
    Load max responsive fraction data from Excel files for all mice.
    
    Returns:
        dict: Dictionary containing data for each mouse and overall statistics
    """
    all_data = {
        'sigmoid_fractions_per_mouse': [],
        'gaussian_fractions_per_mouse': [],
        'mouse_ids': [],
        'sigmoid_means_per_mouse': [],
        'gaussian_means_per_mouse': [],
        'sigmoid_medians_per_mouse': [],
        'gaussian_medians_per_mouse': [],
        'sigmoid_counts_per_mouse': [],
        'gaussian_counts_per_mouse': [],
        'all_sigmoid_fractions': [],
        'all_gaussian_fractions': []
    }
    
    for mouse, day in zip(mice, days):
        print(f"Loading data for {mouse} - {day}")
        
        # Define path to the Excel file
        mouse_path = f'Z:/2p_data/{mouse}/{day}/ML/data/processed_data/auroc_neurometric_zscore_no_sub_v4'
        excel_file = join(mouse_path, 'max_responsive_fraction_analysis.xlsx')
        
        if not os.path.exists(excel_file):
            print(f"Excel file not found: {excel_file}")
            continue
            
        try:
            # Load data from Excel sheets
            sigmoid_df = pd.read_excel(excel_file, sheet_name='Sigmoid_Neurons')
            gaussian_df = pd.read_excel(excel_file, sheet_name='Gaussian_Neurons')

            # save the index of the neurons as array
            np.save(join(mouse_path, 'sigmoid_neuron_indices.npy'), sigmoid_df['Neuron_Index'].values)
            np.save(join(mouse_path, 'gaussian_neuron_indices.npy'), gaussian_df['Neuron_Index'].values)

            # Extract max responsive fractions
            sigmoid_fractions = sigmoid_df['Max_Responsive_Fraction'].values
            gaussian_fractions = gaussian_df['Max_Responsive_Fraction'].values
            
            # Store per-mouse data
            all_data['sigmoid_fractions_per_mouse'].append(sigmoid_fractions)
            all_data['gaussian_fractions_per_mouse'].append(gaussian_fractions)
            all_data['mouse_ids'].append(mouse)
            
            # Calculate per-mouse statistics
            all_data['sigmoid_means_per_mouse'].append(np.mean(sigmoid_fractions))
            all_data['gaussian_means_per_mouse'].append(np.mean(gaussian_fractions))
            all_data['sigmoid_medians_per_mouse'].append(np.median(sigmoid_fractions))
            all_data['gaussian_medians_per_mouse'].append(np.median(gaussian_fractions))
            all_data['sigmoid_counts_per_mouse'].append(len(sigmoid_fractions))
            all_data['gaussian_counts_per_mouse'].append(len(gaussian_fractions))
            
            # Add to overall pools
            all_data['all_sigmoid_fractions'].extend(sigmoid_fractions)
            all_data['all_gaussian_fractions'].extend(gaussian_fractions)
            
            print(f"  Sigmoid neurons: {len(sigmoid_fractions)}, mean fraction: {np.mean(sigmoid_fractions):.3f}")
            print(f"  Gaussian neurons: {len(gaussian_fractions)}, mean fraction: {np.mean(gaussian_fractions):.3f}")
            
        except Exception as e:
            print(f"Error loading data for {mouse} {day}: {e}")
            continue
    
    return all_data

